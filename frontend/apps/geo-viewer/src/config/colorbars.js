export const COLORBAR_OPTIONS = Object.entries(COLORBARS)
	.filter(([value]) => value !== "none")
	.map(([value, meta]) => ({ value, label: meta.label }));

export function colorbarStops(code) {
	return (COLORBARS[code] || COLORBARS.viridis).stops;
}

export function sampleColorbar(code, t) {
	const stops = colorbarStops(code);
	const x = Math.max(0, Math.min(1, t)) * (stops.length - 1);
	const i = Math.min(stops.length - 2, Math.floor(x));
	const f = x - i;
	const a = stops[i];
	const b = stops[i + 1];
	return [
		a[0] + (b[0] - a[0]) * f,
		a[1] + (b[1] - a[1]) * f,
		a[2] + (b[2] - a[2]) * f
	];
}
